/** "NORMAL_OR_MIXED_LOAD" → "Normal or mixed load", "STEAM_REFRESH2" → "Steam refresh". */
export function cycleLabel(name) {
  const words = String(name)
    .replace(/(?<=[A-Z])2$/, '')
    .replace(/_/g, ' ')
    .toLowerCase()
    .trim();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

/** The cycle name of a code, or null (none selected, unknown code). */
export function laundryCycleText(code) {
  const name = LAUNDRY_CYCLES[code];
  return name ? cycleLabel(name) : null;
}
